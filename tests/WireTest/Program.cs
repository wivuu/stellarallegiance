    int afterSecret = o + 1 + Encoding.UTF8.GetByteCount(secret);
    int afterName = afterSecret + 1 + Encoding.UTF8.GetByteCount(name);
    int afterToken = afterName + 1 + Encoding.UTF8.GetByteCount(recon);
    Check(
        HelloMessage.TryParse(full.AsSpan(0, 1), out var h0)
            && h0.Secret == ""
            && h0.Name == ""
