        "Hello bare"
    );
    Check(
        HelloMessage.TryParse(full.AsSpan(0, afterSecret), out var h1)
            && h1.Secret == secret
            && h1.Name == ""
            && h1.ReconnectToken == ""
            && h1.JoinToken == "",
        "Hello prefix: secret only",
        "Hello secret-only"
    );
