int failures = 0;
bool printGoldens = args.Contains("--print-goldens");
var computedGoldens = new List<(string Name, string Value)>();

void Check(bool ok, string pass, string fail)
{
    if (ok)
        Console.WriteLine($"PASS  {pass}");
    else
    {
        Console.WriteLine($"FAIL  {fail}");
        failures++;
    }
}

static string Hex(ReadOnlySpan<byte> b) => Convert.ToHexString(b);

static string Sha(byte[] b) => Convert.ToHexString(SHA256.HashData(b));

static string Diff(byte[] a, byte[] b)
{
    if (a.Length != b.Length)
        return $"length {a.Length} vs {b.Length}";
    for (int i = 0; i < a.Length; i++)
        if (a[i] != b[i])
            return $"first difference at byte {i}: {a[i]:X2} vs {b[i]:X2}";
    return "identical";
}

// Reference bytes (a layout replicated verbatim from the Godot client's hand-packed senders) vs the
// generated codec's output.
void Same(string what, byte[] reference, byte[] generated) =>
    Check(
        reference.AsSpan().SequenceEqual(generated),
        $"{what}: generated bytes == reference bytes ({reference.Length} B)",
        $"{what}: {Diff(reference, generated)}"
    );

void Golden(string name, byte[] bytes, bool hash = true)
{
    string value = hash ? Sha(bytes) : Hex(bytes);
    computedGoldens.Add((name, value));
    if (printGoldens)
        return;
    if (!Goldens.Table.TryGetValue(name, out var expected))
    {
        Check(false, "", $"golden '{name}' missing from the table (run with --print-goldens and paste)");
        return;
    }
    Check(
        expected == value,
        $"golden {name} unchanged",
        $"golden {name} CHANGED: expected {expected} got {value} — a wire layout moved; bump Wire.ProtocolVersion and re-pin"
    );
}

