{
    var v = parse(bytes);
    var again = write(v);
    Check(
        bytes.AsSpan().SequenceEqual(again),
        $"{what}: write → read → write is byte-stable ({bytes.Length} B)",
        $"{what}: re-written bytes differ: {Diff(bytes, again)}"
    );
}

