static bool Near(float a, float b, float tol) => MathF.Abs(a - b) <= tol;

static bool NearV(Vec3 a, Vec3 b, float tol) => Near(a.X, b.X, tol) && Near(a.Y, b.Y, tol) && Near(a.Z, b.Z, tol);

// f16 keeps ~3 significant digits: tolerance relative to magnitude, floored for tiny values.
static bool NearHalf(float a, float b) => Near(a, b, MathF.Max(MathF.Abs(b) * 2e-3f, 1e-3f));

static bool NearHalfV(Vec3 a, Vec3 b) => NearHalf(a.X, b.X) && NearHalf(a.Y, b.Y) && NearHalf(a.Z, b.Z);

