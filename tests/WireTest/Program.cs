        HelloMessage.TryParse(full.AsSpan(0, afterName), out var h2)
            && h2.Secret == secret
            && h2.Name == name
            && h2.ReconnectToken == ""
            && h2.JoinToken == "",
        "Hello prefix: secret + name (v7 shape)",
        "Hello v7"
    );
    Check(
        HelloMessage.TryParse(full.AsSpan(0, afterToken), out var h3) && h3.ReconnectToken == recon && h3.JoinToken == "",
        "Hello prefix: + reconnect token (v9 shape, no join tail)",
        "Hello v9"
    );
