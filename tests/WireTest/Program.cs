    Check(
        HelloMessage.TryParse(full.AsSpan(0, afterSecret + 3), out var mid) && mid.Secret == secret && mid.Name == "",
        "Hello: a name cut mid-string reads as absent (still a valid frame)",
        "Hello mid-field truncation"
    );
    Check(
        HelloMessage.TryParse(full.AsSpan(0, full.Length - 7), out var tj)
            && tj.ReconnectToken == recon
            && tj.JoinToken == "",
        "Hello: a torn join token is ignored, earlier fields survive",
        "Hello torn join"
    );
    // The frames the hub-level tests and the bot hand-build / used to hand-build.
    var smoke = new List<byte> { HelloMessage.MsgId, 0, 5 };
    smoke.AddRange(Encoding.UTF8.GetBytes("smoke"));
    smoke.Add(0);
    Check(
        HelloMessage.TryParse(smoke.ToArray(), out var sm)
            && sm.Name == "smoke"
            && sm.Secret == ""
            && sm.ReconnectToken == ""
            && sm.JoinToken == "",
        "Hello: the tests' 8-byte smoke frame parses",
        "smoke Hello"
    );
    Check(
        HelloMessage.TryParse(new byte[] { 1, 0, 0 }, out var v7) && v7.Name == "" && v7.JoinToken == "",
        "Hello: the old 3-byte simbot frame parses",
        "v7 Hello"
    );
    bool threw = false;
    try
    {
        _ = new HelloMessage { Secret = new string('x', 300) }.ToBytes();
    }
    catch (ArgumentException)
    {
        threw = true;
    }
    Check(threw, "Hello: a u8-length field over 255 bytes throws at build (never a silent wrap)", "Hello oversize build");
}

