// Wire-format codec tests (tests/WireTest). Console PASS/FAIL in the repo's test idiom; exits
// non-zero on any failure.
//
// The generated codecs (tools/wire-gen over shared/Net/Messages.cs + Records.cs) are the ONLY
// definition of the wire format; the server fills them (server/Net/Frames.cs) and the Godot client
// reads them. The legacy hand-written writers were proven byte-identical before they were deleted
// (this suite's history); the goldens in section 8 pin those layouts. Sections:
//
//   1. every fixed record/frame Size and message id matches its literal pin
//   2. entity records + one-shot frames: fill from synthetic sim state, parse back, check every field
//   3. world/content-backed frames on the stock bundle: Welcome (fog off/on), Reveal, Defs, MapList,
//      TeamState, Research, Contacts, Bases, RockUpdates, Loadouts, ConstructorState, Lobby, Stats
//   4. Hello: every field optional — shorter (older) frames and torn tails parse with the rest ""
//   5. client->server frames: the Godot client's hand-packed layouts (replicated here byte for byte)
//      == generated ToBytes(); Spawn's optional tails parse exactly as ClientHub does today
//   6. write -> read -> write round-trips for synthetic instances of every frame (nullable blocks,
//      7-bit strings past 127 bytes, [WireIgnore] fields dropped, u16/u32 counts)
//   7. hostile input: truncation at every prefix length never throws and never parses; count bombs
//      fail without allocating; a wrong id fails
//   8. durable goldens: hex / SHA-256 of synthetic frames pinned so a layout drift is caught
//      (`--print-goldens` regenerates the table after an INTENDED change + a Wire.ProtocolVersion bump)
//
// Run: dotnet run --project tests/WireTest -c Release
